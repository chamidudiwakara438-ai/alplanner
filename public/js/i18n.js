window.t = function (k) {
  const lang = localStorage.getItem('al_lang') || 'en';
  const pack = window.I18N[lang] || window.I18N.en;
  return pack[k] || window.I18N.en[k] || k;
};
window.applyI18n = function () {
  document.querySelectorAll('[data-i]').forEach((el) => { el.textContent = window.t(el.getAttribute('data-i')); });
  const inp = document.getElementById('ai-input');
  if (inp) inp.placeholder = window.t('ai.ph');
  const lb = document.getElementById('lang-btn');
  if (lb) lb.textContent = (localStorage.getItem('al_lang') || 'en').toUpperCase();
};
